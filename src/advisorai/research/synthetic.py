"""Deterministic synthetic snapshot generator (redistributable fixture).

Regenerates ``synthetic-daily-2015-2025-v1/bars.json`` byte-for-byte from a
fixed seed — no market data, free to redistribute. Verified identical across
CPython 3.11/3.12/3.13 (``random.Random.gauss`` is version-stable for a fixed
seed) and byte-identical to the previously committed 856KB JSON, which this
replaces. Full-run reproducibility is preserved: same bytes, same SHA-256,
same replay numerics.
"""

from __future__ import annotations

import hashlib
import json
import random
from datetime import date, timedelta
from pathlib import Path

GENERATOR_VERSION = "advisorai.research.synthetic-generator.v1"
SEED = 20261114
START = date(2015, 1, 2)
END = date(2025, 12, 31)
EXPECTED_SHA256 = "4d30faa638c62190e91beca29a0ffac1ff664ed273ddae09d50ccd15dec35dad"
EXPECTED_COUNTS = {"SPY": 2869, "TLT": 2869}

_EXPOSURES = (
    ("SPY", 200.0, 0.0003, 0.008),
    ("TLT", 120.0, 0.0, 0.006),
)


def generate_bars() -> dict[str, list[dict[str, object]]]:
    """Generate the full synthetic bar set; deterministic for the fixed seed."""
    rng = random.Random(SEED)
    out: dict[str, list[dict[str, object]]] = {}
    for symbol, start, drift, vol in _EXPOSURES:
        rows: list[dict[str, object]] = []
        price = start
        day = START
        while day <= END:
            if day.weekday() < 5:
                price *= 1 + drift + rng.gauss(0, vol)
                price = round(price, 6)
                rows.append(
                    {
                        "date": day.isoformat(),
                        "open": price,
                        "high": round(price * 1.002, 6),
                        "low": round(price * 0.998, 6),
                        "adj_close": price,
                        "volume": 1000000,
                    }
                )
            day += timedelta(days=1)
        out[symbol] = rows
    return out


def bars_payload() -> bytes:
    """The exact committed byte layout: indent=1 JSON plus trailing newline."""
    return (json.dumps(generate_bars(), indent=1) + "\n").encode()


def verify_bytes(payload: bytes) -> str:
    """Verify generated bytes against the pinned hash; return the digest."""
    digest = hashlib.sha256(payload).hexdigest()
    if digest != EXPECTED_SHA256:
        raise ValueError(f"synthetic generator drift: {digest[:16]} != {EXPECTED_SHA256[:16]}")
    return digest


def materialize(snapshot_root: Path) -> Path:
    """Write bars.json + manifest.json into a directory; verify the hash."""
    snapshot_root.mkdir(parents=True, exist_ok=True)
    payload = bars_payload()
    digest = verify_bytes(payload)
    (snapshot_root / "bars.json").write_bytes(payload)
    bars = json.loads(payload.decode())
    manifest = {
        "source": "synthetic-deterministic-v1",
        "generator": f"{GENERATOR_VERSION}; seed={SEED} geometric-walk; NOT market data",
        "license_note": "synthetic fixture, free to redistribute; for CI and contract tests only",
        "interval": "1d",
        "currency": "USD",
        "symbols": ["SPY", "TLT"],
        "bars_sha256": digest,
        "counts": {symbol: len(rows) for symbol, rows in bars.items()},
    }
    if manifest["counts"] != EXPECTED_COUNTS:
        raise ValueError(f"synthetic generator count drift: {manifest['counts']}")
    (snapshot_root / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    return snapshot_root / "bars.json"


